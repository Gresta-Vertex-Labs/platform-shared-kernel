using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Testing;
using SharedKernel.Analyzers.Diagnostics;
using Xunit;

namespace SharedKernel.Analyzers.Tests;

/// <summary>Tests for SK0044 <see cref="LoggerMessageEventIdBareLiteralAnalyzer"/>.</summary>
public class SK0044_LoggerMessageEventIdBareLiteralAnalyzerTests
{
    /// <summary>In-compilation stub with the real constructor and property shapes of the attribute.</summary>
    private const string Stubs = """
        namespace Microsoft.Extensions.Logging
        {
            public enum LogLevel { Debug, Information, Warning }

            [System.AttributeUsage(System.AttributeTargets.Method)]
            public sealed class LoggerMessageAttribute : System.Attribute
            {
                public LoggerMessageAttribute() { }
                public LoggerMessageAttribute(int eventId, LogLevel level, string message) { }
                public LoggerMessageAttribute(LogLevel level, string message) { }
                public int EventId { get; set; }
                public LogLevel Level { get; set; }
                public string? Message { get; set; }
            }
        }
        """;

    private const string EnableSk0044 = "SK0044";

    private static Task VerifyAsync(string source)
    {
        var test = new CSharpAnalyzerTest<LoggerMessageEventIdBareLiteralAnalyzer, DefaultVerifier>
        {
            TestState = { Sources = { Stubs, source } },
        };
        // What a .globalconfig line "dotnet_diagnostic.SK0044.severity = warning" does to the compilation options.
        test.SolutionTransforms.Add((solution, projectId) =>
        {
            var options = (CSharpCompilationOptions)solution.GetProject(projectId)!.CompilationOptions!;
            return solution.WithProjectCompilationOptions(
                projectId,
                options.WithSpecificDiagnosticOptions(options.SpecificDiagnosticOptions.SetItem(EnableSk0044, ReportDiagnostic.Warn))
            );
        });
        return test.RunAsync();
    }

    private const string Usings = """
        using Microsoft.Extensions.Logging;

        """;

    [Fact]
    public Task FirePath_PositionalLiteral_Reports() => VerifyAsync(Usings + """
        public static class Log
        {
            [LoggerMessage({|SK0044:1234|}, LogLevel.Information, "Done.")]
            public static void Done(int count) { }
        }
        """);

    [Fact]
    public Task FirePath_NamedAndParenthesisedLiterals_Report() => VerifyAsync(Usings + """
        public static class Log
        {
            [LoggerMessage(EventId = {|SK0044:42|}, Level = LogLevel.Warning, Message = "Failed.")]
            public static void Failed() { }

            [LoggerMessage(eventId: ({|SK0044:7|}), level: LogLevel.Debug, message: "Parenthesised.")]
            public static void Parenthesised() { }
        }
        """);

    [Fact]
    public Task PassPath_ConstantMemberAccessAndArithmetic_Clean() => VerifyAsync(Usings + """
        public static class Ids
        {
            public const int Base = 1000;
            public const int Done = Base + 1;
        }

        public static class Log
        {
            private const int Local = 2000;

            [LoggerMessage(Ids.Done, LogLevel.Information, "Done.")]
            public static void A() { }

            [LoggerMessage(Local + 5, LogLevel.Information, "Done.")]
            public static void B() { }

            [LoggerMessage(EventId = Ids.Base + 2, Level = LogLevel.Warning, Message = "Failed.")]
            public static void C() { }

            [LoggerMessage(LogLevel.Information, "No event id.")]
            public static void D() { }
        }
        """);

    [Fact]
    public Task PassPath_UnrelatedAttributeWithSameName_Clean() => VerifyAsync("""
        namespace Other
        {
            [System.AttributeUsage(System.AttributeTargets.Method)]
            public sealed class LoggerMessageAttribute : System.Attribute
            {
                public LoggerMessageAttribute(int eventId) { }
            }

            public static class Log
            {
                [LoggerMessage(5)]
                public static void A() { }
            }
        }
        """);

    [Fact]
    public Task PassPath_GeneratedCode_Ignored() => VerifyAsync("// <auto-generated/>\n" + Usings + """
        public static class Log
        {
            [LoggerMessage(1234, LogLevel.Information, "Done.")]
            public static void Done() { }
        }
        """);

    [Fact]
    public async Task NotEnabled_BareLiteral_ProducesNoDiagnostic()
    {
        // The rule ships isEnabledByDefault: false (kernel convention, opt-in for a consuming service): with no
        // configuration the analyzer never reports.
        Assert.False(LoggerMessageEventIdBareLiteralAnalyzer.Rule.IsEnabledByDefault);
        Assert.Equal(DiagnosticSeverity.Warning, LoggerMessageEventIdBareLiteralAnalyzer.Rule.DefaultSeverity);

        var runtimeDirectory = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var compilation = CSharpCompilation.Create(
            "NotEnabled",
            [
                CSharpSyntaxTree.ParseText(Stubs),
                CSharpSyntaxTree.ParseText(
                    Usings + """
                    public static class Log
                    {
                        [LoggerMessage(1234, LogLevel.Information, "Done.")]
                        public static void Done() { }
                    }
                    """),
            ],
            [
                MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
                MetadataReference.CreateFromFile(Path.Combine(runtimeDirectory, "System.Runtime.dll")),
            ],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
        );

        var diagnostics = await compilation
            .WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new LoggerMessageEventIdBareLiteralAnalyzer()))
            .GetAnalyzerDiagnosticsAsync();

        Assert.DoesNotContain(diagnostics, d => d.Id == "SK0044");
    }
}
